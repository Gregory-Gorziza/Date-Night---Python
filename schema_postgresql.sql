CREATE TABLE IF NOT EXISTS visualizacoes_perfil (
    usuario_leitor_id BIGINT NOT NULL REFERENCES "user" (id) ON DELETE CASCADE,
    usuario_alvo_id BIGINT NOT NULL REFERENCES "user" (id) ON DELETE CASCADE,
    contador_aparicoes SMALLINT NOT NULL DEFAULT 0 CHECK (contador_aparicoes BETWEEN 0 AND 3),
    data_ultima_aparicao TIMESTAMPTZ,
    PRIMARY KEY (usuario_leitor_id, usuario_alvo_id),
    CONSTRAINT visualizacoes_perfil_users_different CHECK (usuario_leitor_id <> usuario_alvo_id)
);

CREATE OR REPLACE FUNCTION public.record_profile_view(
    p_reader_id BIGINT,
    p_target_id BIGINT,
    p_expected_count INTEGER
)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    next_count INTEGER;
BEGIN
    IF p_reader_id = p_target_id OR p_expected_count < 0 OR p_expected_count >= 3 THEN
        RAISE EXCEPTION 'Invalid profile view request';
    END IF;

    IF p_expected_count = 0 THEN
        INSERT INTO visualizacoes_perfil (
            usuario_leitor_id, usuario_alvo_id, contador_aparicoes, data_ultima_aparicao
        ) VALUES (p_reader_id, p_target_id, 1, CURRENT_TIMESTAMP)
        ON CONFLICT (usuario_leitor_id, usuario_alvo_id) DO UPDATE
        SET contador_aparicoes = visualizacoes_perfil.contador_aparicoes + 1,
            data_ultima_aparicao = CURRENT_TIMESTAMP
        WHERE visualizacoes_perfil.contador_aparicoes = p_expected_count
        RETURNING contador_aparicoes INTO next_count;
    ELSE
        UPDATE visualizacoes_perfil
        SET contador_aparicoes = contador_aparicoes + 1,
            data_ultima_aparicao = CURRENT_TIMESTAMP
        WHERE usuario_leitor_id = p_reader_id
          AND usuario_alvo_id = p_target_id
          AND contador_aparicoes = p_expected_count
        RETURNING contador_aparicoes INTO next_count;
    END IF;

    IF next_count IS NULL THEN
        SELECT COALESCE(MAX(contador_aparicoes), 0)
        INTO next_count
        FROM visualizacoes_perfil
        WHERE usuario_leitor_id = p_reader_id AND usuario_alvo_id = p_target_id;
    END IF;

    RETURN next_count;
END;
$$;

CREATE OR REPLACE FUNCTION public.update_profile_and_reset_interactions(
    p_user_id BIGINT,
    p_profile JSONB
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    updated_profile public."user";
BEGIN
    SELECT * INTO updated_profile
    FROM public."user"
    WHERE id = p_user_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Profile not found';
    END IF;

    updated_profile := jsonb_populate_record(updated_profile, p_profile);

    UPDATE public."user" SET (
        nome, email, senha, dia, mes, ano, genero, altura, fisico, peso, imc,
        cabelo, pele, tatuagens, fumar, salario, certificacao, tracos, animais,
        musica, artes, esportes, jogos, livros, natureza, viagens, gastronomia,
        causa, pref_genero, dinamica, pref_fisico, pref_tatuagens, pref_fumar,
        ruivo, preto, castanho, loiro, escura, morena, clara, fotos
    ) = (
        updated_profile.nome, updated_profile.email, updated_profile.senha,
        updated_profile.dia, updated_profile.mes, updated_profile.ano,
        updated_profile.genero, updated_profile.altura, updated_profile.fisico,
        updated_profile.peso, updated_profile.imc, updated_profile.cabelo,
        updated_profile.pele, updated_profile.tatuagens, updated_profile.fumar,
        updated_profile.salario, updated_profile.certificacao, updated_profile.tracos,
        updated_profile.animais, updated_profile.musica, updated_profile.artes,
        updated_profile.esportes, updated_profile.jogos, updated_profile.livros,
        updated_profile.natureza, updated_profile.viagens, updated_profile.gastronomia,
        updated_profile.causa, updated_profile.pref_genero, updated_profile.dinamica,
        updated_profile.pref_fisico, updated_profile.pref_tatuagens,
        updated_profile.pref_fumar, updated_profile.ruivo, updated_profile.preto,
        updated_profile.castanho, updated_profile.loiro, updated_profile.escura,
        updated_profile.morena, updated_profile.clara, updated_profile.fotos
    )
    WHERE id = p_user_id;

    DELETE FROM ficha WHERE id_user_a = p_user_id OR id_user_b = p_user_id;
    DELETE FROM visualizacoes_perfil
    WHERE usuario_leitor_id = p_user_id OR usuario_alvo_id = p_user_id;
END;
$$;

